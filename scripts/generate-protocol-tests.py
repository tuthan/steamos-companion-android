#!/usr/bin/env python3
"""Generate named Kotlin fixture tests from docs/protocol-coverage.md."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INVENTORY = ROOT / "docs" / "protocol-coverage.md"
OUTPUT = ROOT / "core/src/test/kotlin/io/github/tuthan/steamoscompanion/core/protocol/ContractFixtureTests.kt"

TEST_COLUMN = re.compile(r"`(?P<class>[A-Za-z]+Test)\.(?P<method>[A-Za-z0-9_]+)`\s*\|")
FIXTURES = re.compile(r"`(?P<fixture>fixtures/[^`]+\.json)`")


def main() -> None:
    groups: dict[str, list[tuple[str, str]]] = {}
    for line in INVENTORY.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        test = TEST_COLUMN.search(line)
        fixtures = FIXTURES.findall(line)
        if not test or len(fixtures) != 1:
            raise SystemExit(f"Cannot generate a test from coverage row: {line}")
        fixture = fixtures[0]
        if fixture.startswith("fixtures/contract/"):
            case = fixture.removeprefix("fixtures/contract/").removesuffix(".json")
            call = f'ProtocolFixtureAssertions.assertContractFixture("{case}")'
        else:
            route = line.split("|", 2)[1].strip().strip("`")
            route_to_enum = {
                "GET /v1/status": "STATUS",
                "GET /v1/display/outputs": "DISPLAY_OUTPUTS",
            }
            if route not in route_to_enum:
                raise SystemExit(f"Legacy body fixture has no route mapping: {route}")
            call = f'ProtocolFixtureAssertions.assertLegacyBody("{fixture}", ApiRoute.{route_to_enum[route]})'
        groups.setdefault(test["class"], []).append((test["method"], call))

    lines = [
        "// Generated by scripts/generate-protocol-tests.py from docs/protocol-coverage.md.",
        "package io.github.tuthan.steamoscompanion.core.protocol",
        "",
        "import org.junit.Test",
        "",
    ]
    for class_name in sorted(groups):
        lines.append(f"class {class_name} {{")
        for method, call in sorted(groups[class_name]):
            lines.append(f"    @Test fun {method}() = {call}")
        lines.extend(["}", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {sum(map(len, groups.values()))} named fixture tests in {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
